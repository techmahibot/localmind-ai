
import json
from datetime import datetime, timezone

from auth import connection


def ensure_chat_tables(conn, postgres):
    """Create conversation and message tables if they don't exist."""

    if postgres:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS conversations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES localmind_users(id)
                    ON DELETE CASCADE,
                title TEXT NOT NULL,
                conversation_type TEXT NOT NULL
                    CHECK (conversation_type IN ('chat', 'document')),
                document_name TEXT,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                conversation_id BIGINT NOT NULL
                    REFERENCES conversations(id) ON DELETE CASCADE,
                role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
                content TEXT NOT NULL,
                sources TEXT,
                created_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_conversations_user
            ON conversations(user_id, updated_at)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_messages_conversation
            ON messages(conversation_id, id)
        """)

    else:
        conn.execute("PRAGMA foreign_keys = ON")

        conn.execute("""
            CREATE TABLE IF NOT EXISTS conversations (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL REFERENCES localmind_users(id)
                    ON DELETE CASCADE,
                title TEXT NOT NULL,
                conversation_type TEXT NOT NULL
                    CHECK (conversation_type IN ('chat', 'document')),
                document_name TEXT,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS messages (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                conversation_id INTEGER NOT NULL
                    REFERENCES conversations(id) ON DELETE CASCADE,
                role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
                content TEXT NOT NULL,
                sources TEXT,
                created_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_conversations_user
            ON conversations(user_id, updated_at)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_messages_conversation
            ON messages(conversation_id, id)
        """)


def initialize_chat_storage():
    """Initialize chat tables using the configured database."""
    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)


def create_conversation(user_id, title, conversation_type="chat",
                        document_name=None):
    """Create a conversation belonging to one user."""

    if conversation_type not in ("chat", "document"):
        raise ValueError("Invalid conversation type.")

    now = datetime.now(timezone.utc).isoformat()

    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)

        if postgres:
            row = conn.execute("""
                INSERT INTO conversations
                    (user_id, title, conversation_type, document_name,
                     created_at, updated_at)
                VALUES (%s, %s, %s, %s, %s, %s)
                RETURNING id
            """, (
                user_id, title, conversation_type, document_name, now, now
            )).fetchone()
            return row[0]

        cursor = conn.execute("""
            INSERT INTO conversations
                (user_id, title, conversation_type, document_name,
                 created_at, updated_at)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (
            user_id, title, conversation_type, document_name, now, now
        ))
        return cursor.lastrowid


def save_message(conversation_id, role, content, sources=None):
    """Save one message in a conversation."""

    if role not in ("user", "assistant"):
        raise ValueError("Invalid message role.")

    now = datetime.now(timezone.utc).isoformat()
    sources_json = (
        json.dumps(sources, ensure_ascii=False)
        if sources is not None else None
    )

    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)

        placeholder = "%s" if postgres else "?"
        conn.execute(
            f"""
            INSERT INTO messages
                (conversation_id, role, content, sources, created_at)
            VALUES ({placeholder}, {placeholder}, {placeholder},
                    {placeholder}, {placeholder})
            """,
            (conversation_id, role, content, sources_json, now)
        )

        conn.execute(
            f"""
            UPDATE conversations
            SET updated_at = {placeholder}
            WHERE id = {placeholder}
            """,
            (now, conversation_id)
        )


def list_conversations(user_id, conversation_type=None):
    """List only conversations owned by the requested user."""

    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)

        if conversation_type:
            placeholder = "%s" if postgres else "?"
            rows = conn.execute(
                f"""
                SELECT id, title, conversation_type, document_name,
                       created_at, updated_at
                FROM conversations
                WHERE user_id = {placeholder}
                  AND conversation_type = {placeholder}
                ORDER BY updated_at DESC
                """,
                (user_id, conversation_type)
            ).fetchall()
        else:
            placeholder = "%s" if postgres else "?"
            rows = conn.execute(
                f"""
                SELECT id, title, conversation_type, document_name,
                       created_at, updated_at
                FROM conversations
                WHERE user_id = {placeholder}
                ORDER BY updated_at DESC
                """,
                (user_id,)
            ).fetchall()

    return [
        {
            "id": row[0],
            "title": row[1],
            "type": row[2],
            "document_name": row[3],
            "created_at": row[4],
            "updated_at": row[5],
        }
        for row in rows
    ]


def get_messages(user_id, conversation_id):
    """Retrieve messages only if the conversation belongs to this user."""

    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)

        placeholder = "%s" if postgres else "?"

        owner = conn.execute(
            f"""
            SELECT id FROM conversations
            WHERE id = {placeholder} AND user_id = {placeholder}
            """,
            (conversation_id, user_id)
        ).fetchone()

        if owner is None:
            return None

        rows = conn.execute(
            f"""
            SELECT id, role, content, sources, created_at
            FROM messages
            WHERE conversation_id = {placeholder}
            ORDER BY id
            """,
            (conversation_id,)
        ).fetchall()

    return [
        {
            "id": row[0],
            "role": row[1],
            "content": row[2],
            "sources": json.loads(row[3]) if row[3] else [],
            "created_at": row[4],
        }
        for row in rows
    ]


def delete_conversation(user_id, conversation_id):
    """Delete a conversation only when it belongs to this user."""

    with connection() as (conn, postgres):
        ensure_chat_tables(conn, postgres)

        placeholder = "%s" if postgres else "?"
        cursor = conn.execute(
            f"""
            DELETE FROM conversations
            WHERE id = {placeholder} AND user_id = {placeholder}
            """,
            (conversation_id, user_id)
        )

        return cursor.rowcount > 0
