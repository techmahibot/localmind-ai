"""Persistent local/hosted user accounts and signed browser sessions."""

import hashlib
import hmac
import os
import re
import secrets
import sqlite3
import time
from contextlib import contextmanager
from pathlib import Path


SESSION_SECONDS = 12 * 60 * 60
PASSWORD_ITERATIONS = 600_000
USERNAME_PATTERN = re.compile(r"^[A-Za-z0-9_]{3,30}$")
LOCAL_DB = Path(__file__).resolve().parent / "localmind.db"


class AuthConfigurationError(Exception):
    pass


class UsernameTaken(Exception):
    pass


def database_url():
    url = os.getenv("DATABASE_URL", "")
    if not url and os.getenv("VERCEL"):
        raise AuthConfigurationError(
            "Account storage is not configured. Connect a PostgreSQL database "
            "and set DATABASE_URL in Vercel."
        )
    return url


def session_secret():
    secret = os.getenv("LOCALMIND_SESSION_SECRET")
    if not secret and os.getenv("VERCEL"):
        raise AuthConfigurationError("Set LOCALMIND_SESSION_SECRET in Vercel.")
    # Local development sessions expire on restart unless a persistent secret is set.
    return secret or _LOCAL_SECRET


_LOCAL_SECRET = secrets.token_hex(32)


@contextmanager
def connection():
    url = database_url()
    if url:
        import psycopg

        conn = psycopg.connect(url, connect_timeout=5)
    else:
        conn = sqlite3.connect(os.getenv("LOCALMIND_DB_PATH", str(LOCAL_DB)), timeout=10)
    try:
        yield conn, bool(url)
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()


def ensure_users_table(conn, postgres):
    if postgres:
        conn.execute(
            "CREATE TABLE IF NOT EXISTS localmind_users ("
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "username TEXT NOT NULL, username_key TEXT NOT NULL UNIQUE, "
            "password_hash TEXT NOT NULL)"
        )
    else:
        conn.execute(
            "CREATE TABLE IF NOT EXISTS localmind_users ("
            "id INTEGER PRIMARY KEY AUTOINCREMENT, "
            "username TEXT NOT NULL, username_key TEXT NOT NULL UNIQUE, "
            "password_hash TEXT NOT NULL)"
        )


def hash_password(password):
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, PASSWORD_ITERATIONS)
    return f"pbkdf2_sha256${PASSWORD_ITERATIONS}${salt.hex()}${digest.hex()}"


def verify_password(password, stored):
    try:
        algorithm, rounds, salt, digest = stored.split("$")
        if algorithm != "pbkdf2_sha256":
            return False
        actual = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), bytes.fromhex(salt), int(rounds))
        return hmac.compare_digest(actual, bytes.fromhex(digest))
    except (ValueError, TypeError):
        return False


def register(username, password):
    username = username.strip()
    if not USERNAME_PATTERN.fullmatch(username):
        raise ValueError("Username must be 3–30 letters, numbers, or underscores.")
    if len(password) < 10 or len(password) > 128:
        raise ValueError("Password must be 10–128 characters.")
    password_hash = hash_password(password)
    with connection() as (conn, postgres):
        ensure_users_table(conn, postgres)
        if postgres:
            row = conn.execute(
                "INSERT INTO localmind_users (username, username_key, password_hash) "
                "VALUES (%s, %s, %s) ON CONFLICT (username_key) DO NOTHING RETURNING id",
                (username, username.lower(), password_hash),
            ).fetchone()
            if row is None:
                raise UsernameTaken()
            return row[0], username
        try:
            cursor = conn.execute(
                "INSERT INTO localmind_users (username, username_key, password_hash) VALUES (?, ?, ?)",
                (username, username.lower(), password_hash),
            )
        except sqlite3.IntegrityError:
            raise UsernameTaken()
        return cursor.lastrowid, username


def find_user(username):
    with connection() as (conn, postgres):
        ensure_users_table(conn, postgres)
        marker = "%s" if postgres else "?"
        return conn.execute(
            f"SELECT id, username, password_hash FROM localmind_users WHERE username_key = {marker}",
            (username.strip().lower(),),
        ).fetchone()


def find_user_by_id(user_id):
    with connection() as (conn, postgres):
        ensure_users_table(conn, postgres)
        marker = "%s" if postgres else "?"
        return conn.execute(
            f"SELECT id, username FROM localmind_users WHERE id = {marker}",
            (user_id,),
        ).fetchone()


def create_session(user_id):
    message = f"{user_id}.{int(time.time())}"
    signature = hmac.new(session_secret().encode(), message.encode(), hashlib.sha256).hexdigest()
    return f"{message}.{signature}"


def session_user_id(token):
    if not token:
        return None
    secret = session_secret()
    try:
        user_id, issued, signature = token.split(".", 2)
        user_id, issued = int(user_id), int(issued)
    except (ValueError, TypeError):
        return None
    if user_id <= 0 or issued > time.time() + 60 or time.time() - issued > SESSION_SECONDS:
        return None
    message = f"{user_id}.{issued}"
    expected = hmac.new(secret.encode(), message.encode(), hashlib.sha256).hexdigest()
    return user_id if hmac.compare_digest(signature, expected) else None
